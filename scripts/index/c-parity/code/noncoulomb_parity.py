"""T-029: P-resolved index of the kernel of the Coulomb-branch restriction, from indices alone.

rho: H -> (functions on the Coulomb branch) restricts classes to Cartan-valued letters.  Its image is the "diagonal
graviton" space of arXiv:2312.16443 (the ring generated by the restricted single-trace gravitons; counted per sector
by fortuity.bmn.gravindex.GravitonCounter).  Fortuitous classes lie in ker(rho) (R-015).  C maps the Cartan to itself
(diag x -> -diag x), so on the image C = (-1)^Y, i.e. every image state has graviton parity P = C (-1)^Y = +1.  Per
SU(3)_R hw column lam:

    O(lam) := (-1)^|lam| ( I   - I_grav^diag )(lam) = sum over ker(rho) of (-1)^Y     (ordinary index)
    T(lam) := (-1)^|lam| I_C(lam) - D(lam)            = sum over ker(rho) of P = #P+ - #P-   (C-twisted index)

with D(lam) = unsigned number of diagonal-graviton states (all 2J).  ker(rho) = non-Coulomb gravitons (P = +1) +
fortuitous classes.  So T(lam) < 0 proves P-odd, hence non-graviton, classes in the column, using only a Haar integral
and the diagonal count (no cohomology computation), PROVIDED D is not overcounted.  [2026-10-02, review C19: the
diagonal counts are random-evaluation lower bounds per weight, but D is their signed Weyl alternation, so it is not a
certified lower bound; see summary/fortuity-summary.pdf, sec. 7.1.]

usage: python3 noncoulomb_parity.py N QMAX   (needs runs/cache/diag_dims_N{N}_j{JMAX}.pkl, JMAX >= 2 QMAX, from diag_counts.py)
       ->  runs/su{N}_kernel_parity_j{2 QMAX}.json
"""
import os, sys, json, time, glob, pickle
import numpy as np
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from twisted_index import SUN, integrate, to_int, hw_multiplicities, RUNS, REPO

INDEX_FILES = {3: 'data/su3/bmn_index_j36.json', 4: 'data/su4/bmn_index_j30.json'}
COH_FILES = {3: ['data/su3/bmn_hw_cohomology_j30.json'],
             4: ['data/su4/bmn_hw_cohomology_j28.json', 'data/su4/bmn_hw_cohomology_j30.json']}
# R-015: non-Coulomb graviton classes (hw columns, all 2J), j <= 30
NONCOULOMB = {3: {(4, 4, 4): 1, (5, 4, 4): 1, (5, 5, 4): 1, (5, 5, 5): 2},
              4: {(6, 4, 4): 1, (7, 4, 4): 2, (6, 5, 4): 1}}


if __name__ == '__main__':
    N = int(sys.argv[1]); Q = int(sys.argv[2])
    t0 = time.time()
    cands = sorted(glob.glob(os.path.join(RUNS, 'cache', f'diag_dims_N{N}_j*.pkl')),
                   key=lambda f: int(f.split('_j')[-1].split('.')[0]))
    cands = [f for f in cands if int(f.split('_j')[-1].split('.')[0]) >= 2 * Q]
    dims = pickle.load(open(cands[0], 'rb'))['dims']
    uns, sig = {}, {}
    for sec, d in dims.items():
        q = tuple(sec[1:])
        if sum(q) <= Q and d:
            uns[q] = uns.get(q, 0) + d
            sig[q] = sig.get(q, 0) + (-1) ** sec[0] * d
    ref = json.load(open(os.path.join(REPO, INDEX_FILES[N])))
    refg = ref['graviton_index_unrefined']
    unref = [sum(v for q, v in sig.items() if sum(q) == d) for d in range(Q + 1)]
    okg = all(unref[d] == refg[2 * d] for d in range(Q + 1) if 2 * d < len(refg))
    print(f'SU({N}) diagonal graviton index vs data (j <= {min(2 * Q, len(refg) - 1)}): {"OK" if okg else "MISMATCH"}',
          flush=True)
    G = SUN(N)
    pl, e1 = to_int(integrate(G, Q, False)[0]) if N == 3 else (None, 0.)
    tw, e2 = to_int(integrate(G, Q, True)[0])
    print(f'indices done, rounding {max(e1, e2):.1e}  ({time.time() - t0:.0f}s)', flush=True)
    hw = lambda w: hw_multiplicities(w, Q)
    H_tw, H_un, H_sg = hw(tw), hw(uns), hw(sig)
    H_pl = hw(pl) if pl is not None else None
    known = {}
    for f in COH_FILES[N]:
        for c in json.load(open(os.path.join(REPO, f)))['columns']:
            known[tuple(c['lam'])] = c
    rows = []
    lams = sorted(set(H_tw) | set(H_un) | set(known), key=lambda l: (sum(l), l))
    for lam in lams:
        if sum(lam) > Q or lam == (0, 0, 0):
            continue
        sgn = (-1) ** sum(lam)
        T = sgn * H_tw.get(lam, 0) - H_un.get(lam, 0)
        row = dict(lam=lam, j=2 * sum(lam), T=T, diag_unsigned=H_un.get(lam, 0))
        if H_pl is not None:
            row['O'] = sgn * (H_pl.get(lam, 0) - H_sg.get(lam, 0))
        if lam in known:
            bh = sum(s['BH'] for s in known[lam]['sectors'])
            row['known'] = dict(total=sum(s['h'] for s in known[lam]['sectors']), BH=bh,
                                noncoulomb=NONCOULOMB[N].get(lam, 0))
            # prediction: T = #nonCoulomb (P+) + #BH_{P+} - #BH_{P-}; only SU(3) (7,4,4) is P-odd (T-029)
            row['T_predicted'] = NONCOULOMB[N].get(lam, 0) - (1 if (N == 3 and lam == (7, 4, 4)) else 0)
        if T != 0 or row.get('O') or row.get('T_predicted'):
            rows.append(row)
    bad = [r for r in rows if 'T_predicted' in r and r['T'] != r['T_predicted']]
    print(f'SU({N}) columns with nonzero kernel index (T = #P+ - #P- in ker rho,  O = sum (-1)^Y over ker rho); '
          f'known range: {sum(1 for r in rows if "T_predicted" in r)} rows, mismatches with prediction {len(bad)}')
    for r in rows:
        flag = '  <-- T<0: P-odd (fortuitous) classes forced' if r['T'] < 0 else ''
        kn = r.get('known')
        kns = f"  known: total={kn['total']} BH={kn['BH']} nonCoulomb={kn['noncoulomb']} (T pred {r['T_predicted']})" if kn else ''
        print(f"  j={r['j']:2} lam={r['lam']}: T={r['T']:3}  O={r.get('O', '-')!s:>3}{kns}{flag}")
    json.dump(dict(description=f'SU({N}) kernel parity indices T = tr(P | ker rho), O = sum_(ker rho) (-1)^Y per hw column',
                   N=N, qmax=Q, diag_source=os.path.basename(cands[0]), rows=rows, mismatches=bad),
              open(os.path.join(RUNS, f'su{N}_kernel_parity_j{2 * Q}.json'), 'w'), indent=1, default=str)

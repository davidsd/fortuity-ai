def rref_add(basis, vec):
    """basis: list of (pivot, dict) in reduced form; returns True if vec added."""
    v = dict(vec)
    for piv, b in basis:
        if piv in v:
            c = v[piv]
            for k, x in b.items():
                v[k] = v.get(k, 0) - c * x
                if v[k] == 0:
                    del v[k]
    if not v:
        return False
    piv = min(v)
    c = v[piv]
    v = {k: Fraction(x) / c for k, x in v.items()}
    # keep reduced: eliminate piv from existing rows
    for i, (p2, b) in enumerate(basis):
        if piv in b:
            cc = b[piv]
            nb = dict(b)
            for k, x in v.items():
                nb[k] = nb.get(k, 0) - cc * x
                if nb[k] == 0:
                    del nb[k]
            basis[i] = (p2, nb)
    basis.append((piv, v))
    return True



def eps(i, j, k):
    p = (i, j, k)
    if len(set(p)) < 3:
        return 0
    inv = sum(1 for x in range(3) for y in range(x + 1, 3) if p[x] > p[y])
    return -1 if inv % 2 else 1


def mono_mul(m1, m2):
    (a1, b1, S1), (a2, b2, S2) = m1, m2
    if S1 & S2:
        return None, 0
    # sign: move each eta of S2 past the etas of S1 with larger index
    sign = 1
    for k in range(3):
        if S2 >> k & 1:
            for l in range(k + 1, 3):
                if S1 >> l & 1:
                    sign = -sign
    return (tuple(x + y for x, y in zip(a1, a2)), b1 + b2, S1 | S2), sign


def pmul(p1, p2):
    out = {}
    for m1, c1 in p1.items():
        for m2, c2 in p2.items():
            m, s = mono_mul(m1, m2)
            if s:
                out[m] = out.get(m, 0) + s * c1 * c2
    return {m: c for m, c in out.items() if c}


